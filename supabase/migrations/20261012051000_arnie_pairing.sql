-- =====================================================================
-- Connecting a computer without copying anything.
--
-- The agent's only way in was: open Settings, reveal a token, copy it, open a
-- terminal, paste it into a command. Bryce, on reviewing it: "we are building
-- for lots of users so it needs to be easy as hell or people won't use it."
-- He is right — nobody outside the room that built it would ever do that, and
-- everything in the Computer tab is unreachable until this is gone.
--
-- THE SHAPE is the one every device-pairing flow uses, because it is the only
-- one that works when the thing being paired cannot sign in:
--
--   1. The agent asks for a CODE. It has no account and no token, so this one
--      call is public — the code it gets back is a high-entropy secret and
--      the only thing it can do is wait.
--   2. The agent opens the browser at /connect?code=… The person is ALREADY
--      signed in there, which is the whole trick: their session does the
--      authenticating, not a string they typed.
--   3. They see which computer is asking and press Connect. The browser —
--      authenticated as them — attaches their refresh token to the code.
--   4. The agent's next poll collects it, and the row is deleted in the same
--      breath.
--
-- THE SECRET AT REST is the part to be careful about, so: two minutes to
-- live, read exactly once, deleted on read, and never readable by anybody
-- through the API — RLS grants nothing to `authenticated`, so the only way in
-- or out is the pairing function running as the service role. A row that is
-- never collected expires and is swept.
--
-- The CODE is not a password and is not typed by anybody: it is generated by
-- the agent, carried in a URL the agent itself opens, and useless after one
-- claim. What authorises the pairing is the signed-in session in the browser.
-- =====================================================================

create table if not exists public.arnie_pairings (
  -- The code the agent generated. High entropy; this is the join key, not a
  -- guessable sequence.
  code           text primary key,
  -- A second secret the agent keeps to itself, so that knowing the code (it
  -- travels in a URL) is not enough to COLLECT the token — only the process
  -- that started the pairing can finish it.
  poll_secret    text not null,
  device_label   text,
  platform       text,
  agent_version  text,
  -- Filled in by the browser, as the person, at the moment they press
  -- Connect. Null until then; deleted the instant the agent reads it.
  refresh_token  text,
  company_id     integer references public.companies(id) on delete cascade,
  employee_id    integer references public.employees(id) on delete cascade,
  claimed_at     timestamptz,
  created_at     timestamptz not null default now(),
  expires_at     timestamptz not null default (now() + interval '2 minutes')
);

create index if not exists arnie_pairings_expiry_idx on public.arnie_pairings (expires_at);

-- RLS on, and NO policy for `authenticated` on purpose. Nothing signed in can
-- read a pairing row, which means a token in flight is not reachable through
-- the API by anyone — including the person it belongs to. The pairing
-- function holds the service role and is the only way through.
alter table public.arnie_pairings enable row level security;

do $$ begin
  create policy service_role_all on public.arnie_pairings
    for all to service_role using (true) with check (true);
exception when duplicate_object then null; end $$;

-- Anything nobody collected. Called by the pairing function on every start,
-- so there is no cron to forget: the table cannot grow without new pairings,
-- and a new pairing is exactly when sweeping is free.
create or replace function public.arnie_sweep_pairings()
returns void
language sql
security definer
set search_path = 'public', 'pg_temp'
as $$
  delete from public.arnie_pairings where expires_at < now();
$$;
