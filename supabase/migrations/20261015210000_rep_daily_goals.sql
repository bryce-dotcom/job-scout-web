-- A sales lead's daily goals for his reps, and the scoreboard against them.
--
-- Cole runs a huddle every morning and a follow-up about 4pm. He wants Jenny
-- to ask him each workday for his reps' goals — estimates created, meetings
-- attended, estimates won — ("or say same as yesterday"), then hold the day's
-- JobScout numbers up against them. (Bryce, 2026-10-15.)
--
-- rep_goal_boards: WHO a lead tracks. One row per lead.
-- rep_daily_goals: one row per rep per day. NULL = no goal set for that
--   number, which is different from a goal of 0.

create table if not exists public.rep_goal_boards (
  id          bigint generated by default as identity primary key,
  company_id  integer not null,
  owner_employee_id integer not null,
  rep_ids     integer[] not null default '{}',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (company_id, owner_employee_id)
);

create table if not exists public.rep_daily_goals (
  id          bigint generated by default as identity primary key,
  company_id  integer not null,
  rep_employee_id integer not null,
  goal_date   date not null,
  estimates_created  integer check (estimates_created is null or estimates_created >= 0),
  meetings_attended  integer check (meetings_attended is null or meetings_attended >= 0),
  estimates_won      integer check (estimates_won is null or estimates_won >= 0),
  set_by_employee_id integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (company_id, rep_employee_id, goal_date)
);
create index if not exists rep_daily_goals_day on public.rep_daily_goals (company_id, goal_date);

alter table public.rep_goal_boards enable row level security;
alter table public.rep_daily_goals enable row level security;

do $$ begin
  create policy rep_goal_boards_select on public.rep_goal_boards for select
    using (company_id in (select public.current_user_company_ids()));
  create policy rep_goal_boards_write on public.rep_goal_boards for all
    using (company_id in (select public.current_user_company_ids()) and public.current_user_access_level() >= 2)
    with check (company_id in (select public.current_user_company_ids()) and public.current_user_access_level() >= 2);
  create policy rep_daily_goals_select on public.rep_daily_goals for select
    using (company_id in (select public.current_user_company_ids()));
  create policy rep_daily_goals_write on public.rep_daily_goals for all
    using (company_id in (select public.current_user_company_ids()) and public.current_user_access_level() >= 2)
    with check (company_id in (select public.current_user_company_ids()) and public.current_user_access_level() >= 2);
exception when duplicate_object then null; end $$;
