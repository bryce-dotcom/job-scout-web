#!/usr/bin/env node
// Renders the feature knowledge cards (src/lib/featureKnowledge) into
// supabase/functions/_shared/arnieKnowledgeCards.ts, so arnie-chat can build
// Arnie's instructions on the SERVER with the same knowledge the browser had.
//
//   node scripts/build-arnie-knowledge.mjs          write the file
//   node scripts/build-arnie-knowledge.mjs --check  exit 1 if it is stale
//
// guard.mjs runs --check on every build, so a card edited without
// regenerating fails the build instead of leaving Arnie on the old text.
// After regenerating, deploy arnie-chat (npm run arnie:deploy -- arnie-chat).

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = resolve(root, 'supabase/functions/_shared/arnieKnowledgeCards.ts')

const { KNOWLEDGE_CARDS_LIST } = await import(pathToFileURL(resolve(root, 'src/lib/featureKnowledge/index.js')).href)
const { featureIndex, indexCard } = await import(pathToFileURL(resolve(root, 'supabase/functions/_shared/arnieKnowledgeMatch.ts')).href)

const cards = KNOWLEDGE_CARDS_LIST.map(indexCard)
const body = `// GENERATED by scripts/build-arnie-knowledge.mjs from src/lib/featureKnowledge.
// Do not edit by hand — edit the card, then run:
//   node scripts/build-arnie-knowledge.mjs && npm run arnie:deploy -- arnie-chat
// guard.mjs fails the build when this file is out of date.

import type { IndexedCard } from './arnieKnowledgeMatch.ts'

export const FEATURE_INDEX: string = ${JSON.stringify(featureIndex(KNOWLEDGE_CARDS_LIST))}

export const INDEXED_CARDS: IndexedCard[] = ${JSON.stringify(cards, null, 1)}
`

const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : ''
if (process.argv.includes('--check')) {
  if (current !== body) {
    console.error('arnie knowledge: supabase/functions/_shared/arnieKnowledgeCards.ts is out of date with the feature cards.')
    console.error('  Run: node scripts/build-arnie-knowledge.mjs   then deploy arnie-chat.')
    process.exit(1)
  }
  console.log(`arnie knowledge: up to date (${cards.length} cards)`)
} else {
  writeFileSync(OUT, body)
  console.log(`arnie knowledge: wrote ${cards.length} cards, ${(body.length / 1024).toFixed(0)} KB`)
}
